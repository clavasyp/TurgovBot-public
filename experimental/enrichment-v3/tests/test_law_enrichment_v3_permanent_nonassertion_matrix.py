def test_v3_action_local_nonassertion_matrix_bookkeeping() -> None:
    """Таблица не должна разъезжаться с замером при правках вручную."""

    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5
    assert len({case[0] for case in CASES}) == len(CASES) == 206

    divergent: list[str] = []
    holes: list[str] = []
    false_blocks: list[str] = []
    for case_id, _source, _output, expected, measured, note in CASES:
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        assert note.strip(), case_id
        pairs = [
            index
            for index in range(5)
            if expected[index] != measured[index]
        ]
        if not pairs:
            assert case_id not in XFAIL_REASONS, case_id
            continue
        divergent.extend(f"{case_id}-{PATH_IDS[index]}" for index in pairs)
        assert case_id in XFAIL_REASONS, case_id
        if any(measured[index] == "P" for index in pairs):
            holes.append(case_id)
        else:
            false_blocks.append(case_id)

    # ЗАМЕР ПОСЛЕ ВОЛНЫ 9.  Волна 9 закрыла 11 случаев класса M (49 пар:
    # ветвь «по словам X» — M04/M06/M08 по пять пар, M14/M16/M18 по три, —
    # и вся ветвь зачина «как утвержда…» M47-M51 по пять), поэтому дыр стало
    # 29 - 11 = 18, а расходящихся параметров 174 - 49 = 125.  Семь ложных
    # блоков волна 9 не трогала.
    assert len(holes) == 18
    assert len(false_blocks) == 7
    assert len(divergent) == 125
    assert set(XFAIL_REASONS) == set(holes) | set(false_blocks)
    assert len(CLOSED_BY_WAVE7) == 7
    assert len(CLOSED_BY_WAVE8) == 45
    assert len(CLOSED_BY_WAVE9) == 11
    assert [wave for wave, _closed in CLOSED_HISTORY] == ["7", "8", "9"]
    assert [closed for _wave, closed in CLOSED_HISTORY] == [
        CLOSED_BY_WAVE7,
        CLOSED_BY_WAVE8,
        CLOSED_BY_WAVE9,
    ]

    # История работает СТОРОЖЕМ: причина закрытого случая не выбрасывается, а
    # переезжает в свою волну, и с этого момента случай обязан совпадать с
    # доктриной.  Повторное открытие дыры роняет матрицу здесь же, даже если
    # причину «потеряют» по дороге.
    ids = {case[0] for case in CASES}
    seen_closed: set[str] = set()
    for wave, closed in CLOSED_HISTORY:
        assert closed, wave
        assert set(closed) <= ids, wave
        # причина не может быть одновременно живой и историей…
        assert not set(closed) & set(XFAIL_REASONS), wave
        # …и не может лежать в двух волнах сразу
        assert not set(closed) & seen_closed, wave
        seen_closed |= set(closed)
        for closed_id, reason in closed.items():
            assert reason.strip(), closed_id
            case = next(c for c in CASES if c[0] == closed_id)
            assert case[3] == case[4], closed_id
    assert len(seen_closed) == 63


