# КОНТРАКТ АБЛЯЦИИ (укрепление прибора, волна A5-B).
#
# Записанная дыра класса «ведущий маркер» держится не на одном прогоне, а на
# ПАРЕ: тот же источник, тот же вывод БЕЗ ведущего маркера. Если близнец без
# маркера ведёт себя ровно по доктрине, значит нечестность вывода прибор
# видеть умеет — и снял её именно маркер. Без близнеца «дыра» могла бы
# оказаться артефактом непарсящегося вывода, а «верный блок» — совпадением.
#
# Контракт ПОЛНЫЙ, а не выборочный: он применяется к каждому случаю таблицы,
# чей вывод начинается (в любой своей клаузе) с маркера любого из двух
# инвентарей валидатора плюс смежных ведущих оборотов. Двум случаям, которые
# достались от волны 7, близнеца не хватало — он измерен и добавлен
# (abl-real-esli-keep, abl2-real-esli-keep), поэтому исключений в контракте
# нет вовсе.
_ABLATION_LEAD_MARKERS: tuple[str, ...] = (
    # многословные — первыми, иначе короткий вариант съест префикс
    "несмотря на то что",
    "для того чтобы",
    "имеет право",
    "при аварии",
    "для проведения",
    "в случае",
    "при условии",
    "как правило",
    "что важно",
    # _GENERIC_MODAL_SUBORDINATE_RE
    "чтобы",
    "дабы",
    "если",
    "когда",
    "пока",
    "поскольку",
    "хотя",
    # _GENERIC_MODAL_RE
    "обязана",
    "должна",
    "может",
    "вправе",
    "надлежит",
    "нужно",
    "необходимо",
    "следует",
    "можно",
    "разрешается",
    "разрешено",
    "допускается",
    "требуется",
    "нельзя",
    "запрещается",
)
_ABLATION_CLAUSE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+")


def _ablate_leading_markers(text: str) -> str:
    """Снять ведущие маркеры в голове каждой клаузы вывода."""

    clauses: list[str] = []
    for clause in _ABLATION_CLAUSE_SPLIT_RE.split(text):
        touched = False
        while True:
            lowered = clause.lower()
            hit = next(
                (
                    marker
                    for marker in _ABLATION_LEAD_MARKERS
                    if lowered.startswith(marker + " ")
                ),
                None,
            )
            if hit is None:
                break
            clause = clause[len(hit) + 1:]
            touched = True
        if touched and clause:
            clause = clause[0].upper() + clause[1:]
        clauses.append(clause)
    return " ".join(clauses)


def test_leading_marker_cases_carry_an_ablation_twin() -> None:
    """Каждый ведущий маркер обязан иметь в таблице близнеца без него."""

    # сама абляция обязана оставаться работающей, а не тождеством
    assert _ablate_leading_markers(
        "Чтобы организация пишет штраф"
    ) == "Организация пишет штраф"
    assert _ablate_leading_markers(
        "Комиссия пишет штраф. Чтобы организация пишет арест"
    ) == "Комиссия пишет штраф. Организация пишет арест"
    assert _ablate_leading_markers(
        "Организация чтобы пишет штраф"
    ) == "Организация чтобы пишет штраф"
    assert _ablate_leading_markers(
        "Организация «Чтобы» пишет штраф"
    ) == "Организация «Чтобы» пишет штраф"

    by_key = {(case[1], case[2]): case for case in CASES}
    covered: list[str] = []
    for case_id, source, output, _expected, _measured, _note in CASES:
        ablated = _ablate_leading_markers(output)
        if ablated == output:
            continue
        covered.append(case_id)
        twin = by_key.get((source, ablated))
        assert twin is not None, (case_id, ablated)
        # близнец обязан вести себя ПО ДОКТРИНЕ: только тогда доказано, что
        # прибор видит нечестность вывода и что снял её именно маркер
        assert twin[3] == twin[4], (case_id, twin[0], twin[3], twin[4])
        # близнец не имеет права быть тем же самым случаем
        assert twin[0] != case_id, case_id
    assert len(covered) == 94
