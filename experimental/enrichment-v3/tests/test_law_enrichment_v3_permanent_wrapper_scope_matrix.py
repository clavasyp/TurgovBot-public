    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5

    # 1. сама доктрина обязана оставаться различающей, а не константой
    assert _doctrine_expectation(
        "Организация пишет арест. Комиссия пишет штраф.",
        "Организация пишет арест",
    ) == "PPPPP"
    assert _doctrine_expectation(
        "Организация пишет арест. Комиссия пишет штраф.",
        "Организация пишет штраф",
    ) == "RRRRR"
    assert _doctrine_expectation(
        "Организация пишет арест. Комиссия пишет штраф.",
        "Комиссия пишет арест",
    ) == "RRRRR"
    assert _doctrine_expectation(
        "Организация «Чтобы» пишет арест.",
        "Организация пишет арест",
    ) == "PPPPP"
    assert _doctrine_expectation(
        "Организация пишет арест.",
        "Организация {Чтобы} пишет арест",
    ) == "RRRRR"

    # 2. форма таблицы и МАШИННО выведенная колонка expected
    case_ids = [case[0] for case in CASES]
    assert len(set(case_ids)) == len(case_ids) == 308

    holes: set[str] = set()
    false_blocks: set[str] = set()
    divergent_params: list[str] = []
    for case_id, source, output, expected, measured, note in CASES:
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        assert source and output and note.strip(), case_id
        if case_id in DOCTRINE_BY_PRESCRIPTION:
            assert expected == "PPPPP", case_id
        else:
            assert expected == _doctrine_expectation(source, output), case_id
        for index in range(5):
            if expected[index] == measured[index]:
                continue
            divergent_params.append(f"{case_id}-{PATH_IDS[index]}")
            if measured[index] == "P":
                holes.add(case_id)
            else:
                false_blocks.add(case_id)
        # Пояснение не имеет права называть дырой или ложным блоком то,
        # что замер закрыл, не оставив следа.  Закрытый случай сохраняет в
        # заметке ИСТОРИЮ дефекта, поэтому слова «ДЫРА» и «ЛОЖНЫЙ БЛОК» у
