def test_inline_authority_roster_inherits_actors_and_exclusions() -> None:
    source = (
        "Список лиц, уполномоченных выписать ордер типа CS: "
        "Сотрудники LSCSD, LSPD, FIB, GOV.\n"
        "Исключение:\n"
        "Сотрудники, проходящие стажировку (кадеты)"
    )
    validate_synonym_source_evidence(
        source,
        [
            "сотрудники LSCSD выдают ордер CS",
            "FIB уполномочен выписать ордер CS",
            "кадетам запрещено выписывать ордер CS",
        ],
    )


