def get_case_file_draft_prompt(
    complaint_title: str,
    complaint_content: str,
    facts_with_verdict: list,
    law_sections_text: str,
    requirements_text: str = ""
) -> str:
    """
    Генерирует промпт для создания черновика кейс-файла.

    Точно повторяет логику из caseFileDraftService.js generateCaseFileDraft.

    Args:
        complaint_title: Заголовок жалобы
        complaint_content: Текст жалобы
        facts_with_verdict: Список фактов с пометкой прокурора
        law_sections_text: Текст релевантных статей законов
        requirements_text: Требования заявителя (опционально)

    Returns:
        Строка с промптом для AI
    """
    # Форматируем факты с пометками прокурора
    verdict_label = {"TRUE": "правдивый", "FALSE": "ложный"}

    facts_lines = []
    for fact in facts_with_verdict:
        text = fact.get("text", "").strip()
        status = fact.get("status", "")
        legal_pos = fact.get("legalPositionText", "")
        legal_status = fact.get("legalPositionStatus", "")

        if not text or status not in ("TRUE", "FALSE"):
            continue

        line = f"{text} (пометка прокурора: {verdict_label.get(status, status)})"

        if legal_pos and legal_pos.strip():
            if legal_status == "TRUE":
                line += f". Правовая квалификация (принята): {legal_pos.strip()}"
            elif legal_status == "FALSE":
                line += f". Правовая квалификация (отклонена прокурором): {legal_pos.strip()}"
            else:
                line += f". Правовая квалификация: {legal_pos.strip()}"

        facts_lines.append(line)

    facts_text = "\n".join(facts_lines) if facts_lines else "(нет фактов с пометкой прокурора)"

    # Ограничиваем размер текстов
    complaint_full = (complaint_title or "") + "\n\n" + (complaint_content or "")
    complaint_full = complaint_full[:12000]
    law_sections_text = (law_sections_text or "")[:15000]

    requirements_section = ""
    if requirements_text:
        requirements_section = f"\nТРЕБОВАНИЯ ЗАЯВИТЕЛЯ (учитывай при выборе типа решения и наказания): {requirements_text}\n"

    return f"""Ты — помощник прокурора. По материалам жалобы и фрагментам законов сформируй поля для кейс-файла (дело о привлечении к ответственности). Дело — финальный официальный документ: в тексте полей не должно быть черновиков, открытых вопросов, формулировок вроде «нужно уточнить», «предположительно», «на усмотрение». Только утвердительные формулировки. Повествование ведётся от лица прокурора в официальном стиле офиса Генерального прокурора.

ЖАЛОБА (заголовок и содержание) — только как контекст для понимания:
{complaint_full}

ФАКТЫ С ПОМЕТКОЙ ПРОКУРОРА — только как контекст; в текст полей дела эти пометки включать нельзя:
{facts_text}

ФРАГМЕНТЫ ЗАКОНОВ (релевантные статьи):
{law_sections_text or '(нет фрагментов)'}
{requirements_section}
Требования к полям (все поля — финальный текст, без черновиков и без пометок прокурора в выводе):
- FACTS: фактические обстоятельства от лица прокурора. Список «ФАКТЫ С ПОМЕТКОЙ ПРОКУРОРА» используй только как контекст: включай в установленные факты лишь то, что прокурор отметил как правдивый; ложные не включай. В самом тексте поля FACTS не пиши «правдивый», «ложный», «пометка прокурора» — это только для твоего понимания. Итог — связный финальный абзац; при наличии видео — «На предоставленном видео видно:» и буллеты.
- OVERVIEW_OF_VIOLATION: краткий обзор нарушения (напр. «3.1 Нарушение Этического кодекса»).
- LAW_CITING: применимость закона (кодекс распространяется на..., обязателен для...). Процессуальные моменты (нарушил процессуальный кодекс => УК) — здесь или в FACTS_CONNECTED_WITH_LAW, не в ARTICLES_VIOLATED.
- FACTS_CONNECTED_WITH_LAW: связь фактов со статьями — «Действия [имя] нарушают: ст. N ЭК (суть), ст. M ЭК (суть)».
- TYPE_OF_CRIME: «преступление», «административное правонарушение» или другое по ситуации.
- ARTICLES_VIOLATED: только статьи из УК, АК, ЭК (напр. «ЭК ст. 16, ст. 20»). Учитывай «Правовая квалификация» по фактам при согласовании с фрагментами законов.
- PENALTY: наказание по этим статьям (суммы, вид — из закона). Учитывай требования заявителя при выборе типа решения, если они указаны выше.

Дело — финальный документ: без черновиков, без открытых вопросов, без пометок прокурора (правдивый/ложный) в выводе. Повествование от лица прокурора, официальный стиль офиса Генерального прокурора.

Ответь только JSON по заданной схеме, без markdown."""


