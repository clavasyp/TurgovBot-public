def test_actorless_multi_modifier_penalty_harness_reaches_relation_gate() -> None:
    """Оба penalty-пути обязаны доходить до разбора отношения, а не до предусловия.

    Без этого R в двух правых колонках были бы ложными: отказ на предусловии
    неотличим от сработавшего гейта по одному лишь исходу.
    """

    by_id = {case[0]: case for case in CASES}
    penalty_paths = (_validate_penalty_summary, _validate_penalty_other)

    # 1. Контроль класса: дословный вывод обязан пройти обе penalty-ноги.
    _cid, source, output, expected, measured, _note = by_id["G1-exact"]
    assert expected == measured == "PPPPP"
    for validate in penalty_paths:
        validate(source, output)

    # 2. Нечестный вывод обязан упасть НЕ на предусловии.
    for case_id in ("G1-change", "G1-free"):
        _cid, source, output, expected, measured, _note = by_id[case_id]
        assert expected == measured == "RRRRR"
        for validate in penalty_paths:
            with pytest.raises(ValueError) as excinfo:
                validate(source, output)
            message = str(excinfo.value)
            for bail in _PRECONDITION_BAILS:
                assert bail not in message, "%s: %s" % (case_id, message)

    # 3. Предписанная контрольная тройка на носителе с актором и пациентом.
    for validate in penalty_paths:
        validate(_HARNESS_SOURCE, _HARNESS_FAITHFUL)
    for unfaithful in (_HARNESS_PATIENT_SWAP, _HARNESS_ACTOR_SWAP):
        for validate in penalty_paths:
            with pytest.raises(ValueError) as excinfo:
                validate(_HARNESS_SOURCE, unfaithful)
            message = str(excinfo.value)
            for bail in _PRECONDITION_BAILS:
                assert bail not in message, "%s: %s" % (unfaithful, message)
