    assert len(holes) == 25
    assert len(false_blocks) == 11
    assert len(divergent) == 147

    # (4) у каждого носителя есть дословный случай — иначе R на нечестных
    # выводах этого носителя нельзя отличить от отказа предусловия.
    for source, literals in literal_by_source.items():
        assert literals, source

