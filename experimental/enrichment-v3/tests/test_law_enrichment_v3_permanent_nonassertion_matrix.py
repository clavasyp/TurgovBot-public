def _squeeze_surface(text: str) -> str:
    """Схлопнуть пробелы и регистр — для сравнения пары с её абляцией."""

    return re.sub(r"\s+", " ", text).strip().casefold()


def _strip_one_marker(output: str) -> str:
    """Снять ровно один эпистемический маркер с вывода."""

    surface = output.strip()
    for marker in OUTPUT_SIDE_LAUNDERING_MARKERS:
        if marker == "?":
            continue
        if marker.startswith(",") and surface.endswith(marker):
            return surface[: -len(marker)].strip()
        if surface.startswith(marker):
            return surface[len(marker):].strip()
    return surface.rstrip("? ").strip()


def _matrix_params() -> tuple[object, ...]:
    params: list[object] = []
    for case_id, source, output, expected, measured, note in CASES:
        del note
        for index, path_id in enumerate(PATH_IDS):
            validate = ALL_OUTPUT_PATHS[index]
            expects_raise = expected[index] == "R"
            param_id = f"{case_id}-{path_id}"
            if measured[index] == expected[index]:
                params.append(
                    pytest.param(
                        source,
                        output,
                        expects_raise,
                        validate,
                        id=param_id,
                    )
                )
                continue
            params.append(
                pytest.param(
                    source,
                    output,
                    expects_raise,
                    validate,
                    id=param_id,
                    marks=pytest.mark.xfail(
                        strict=True,
                        reason=XFAIL_REASONS[case_id],
                    ),
                )
            )
    return tuple(params)


