    """Пояснительный слой не имеет права описывать мир до правки."""

    closed_wave = {
        case_id: wave for wave, closed in CLOSED_HISTORY for case_id in closed
    }
    for case_id, _source, _output, expected, measured, note in CASES:
        pairs = [index for index in range(5) if expected[index] != measured[index]]
        leaks = [index for index in pairs if measured[index] == "P"]
