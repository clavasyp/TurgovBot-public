def test_v3_interrogative_scope_matrix_bookkeeping() -> None:
    """Прибор сторожит сам себя: доктрина, счётчики, словарь причин, обвязка."""

    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5

    all_cases = CASES + LEADING_CLAUSE_CASES
    by_id = {case[0]: case for case in all_cases}
    assert len(by_id) == len(all_cases) == 116 + 32
    assert len(CASES) == 116
    assert len(LEADING_CLAUSE_CASES) == 32

    divergent: list[str] = []
    hole_cases: list[str] = []
    block_cases: list[str] = []
    divergent_params = 0
    hole_params = 0
    block_params = 0
    for case_id, source, output, expected, measured, note in all_cases:
        assert source and output and note.strip(), case_id
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        # ГЛАВНАЯ защита: доктрину нельзя ослабить правкой буквы в expected —
        # она выводится из имени случая.
        assert expected == _doctrine_expected(case_id), case_id
        mismatched = [
            index for index in range(5) if expected[index] != measured[index]
        ]
        if not mismatched:
            assert case_id not in DIVERGENCE_MECHANISM, case_id
            continue
        assert case_id in DIVERGENCE_MECHANISM, case_id
        divergent.append(case_id)
        divergent_params += len(mismatched)
        holes = sum(1 for index in mismatched if measured[index] == "P")
        blocks = len(mismatched) - holes
        hole_params += holes
        block_params += blocks
        if holes:
            hole_cases.append(case_id)
        if blocks:
            block_cases.append(case_id)

    assert set(DIVERGENCE_MECHANISM) == set(divergent)
    assert len(CLOSED_BY_WAVE8) == 41
    assert not set(CLOSED_BY_WAVE8) & set(DIVERGENCE_MECHANISM)
    assert set(CLOSED_BY_WAVE8) <= set(by_id)
    for closed_id in CLOSED_BY_WAVE8:
        case = by_id[closed_id]
        assert case[3] == case[4], closed_id
    assert len(divergent) == 8
    assert len(hole_cases) == 6
    assert len(block_cases) == 2
    assert divergent_params == 35
    assert hole_params == 28
    assert block_params == 7
    assert hole_params + block_params == divergent_params
    assert len(all_cases) * 5 == 740

    for case_id, (mechanism, root) in DIVERGENCE_MECHANISM.items():
        assert case_id in by_id, case_id
        assert mechanism.strip(), case_id
        assert root.startswith("services/law_enrichment_validation.py:"), case_id

    # Обвязка: каждая тройка живости стоит на ОДНОМ источнике, дословный вывод
    # проходит все пять путей, нечестный — падает на всех пяти. Без этого
    # penalty-буквы R были бы отказами по предусловию, а не измерением.
    assert len(PENALTY_LIVENESS_CONTROLS) == 13
    for label, faithful_id, dishonest_ids in PENALTY_LIVENESS_CONTROLS:
        assert label.strip()
        faithful = by_id[faithful_id]
        assert faithful[3] == faithful[4] == "PPPPP", faithful_id
        assert dishonest_ids, label
        for dishonest_id in dishonest_ids:
            dishonest = by_id[dishonest_id]
            assert dishonest[1] == faithful[1], (faithful_id, dishonest_id)
            assert dishonest[3] == dishonest[4] == "RRRRR", dishonest_id

    # Ни один xfail не должен опираться на случай, которого нет в таблицах.
    assert set(DIVERGENCE_MECHANISM) <= set(by_id)
