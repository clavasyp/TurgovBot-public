# ------------------------------------------------------------------- ДОКТРИНА
# Колонка expected не пишется рядом со случаем — она ВЫВОДИТСЯ ИЗ ЕГО ИМЕНИ.
# Суффикс имени обязан попасть ровно в ОДИН из двух белых списков; имя, попавшее
# в оба списка или ни в один, роняет самопроверку.  Без этого записанную дыру
# можно закрасить правкой одной буквы в expected, и прибор молча подделается.
_HONEST_SUFFIXES = (
    "-exact",  # дословное эхо источника: обязано пройти все пять путей
)
_DISHONEST_SUFFIXES = (
    "-free",  # выдуманный ЛИШНИЙ модификатор, которого в источнике нет
    "-change",  # подмена модификатора на другой
    "-drop",  # потеря модификатора, который источник несёт
)


def _doctrine_expected(case_id: str) -> str:
    """Пять букв, которых требует доктрина, по одному лишь имени случая."""

    honest = any(case_id.endswith(suffix) for suffix in _HONEST_SUFFIXES)
    dishonest = any(case_id.endswith(suffix) for suffix in _DISHONEST_SUFFIXES)
    if honest == dishonest:
        raise AssertionError(
            f"имя случая {case_id!r} не относит его ни к честным, ни к "
            "нечестным выводам однозначно: суффикс обязан попасть ровно в "
            "один из двух белых списков"
        )
    return "PPPPP" if honest else "RRRRR"


def _doctrine_white_lists_are_sound() -> None:
    """Белые списки обязаны быть взаимно однозначны и целиком рабочими.

    Ни один суффикс одного списка не смеет оканчиваться суффиксом другого —
    иначе имя попадёт сразу в оба.  И ни один суффикс не смеет быть мёртвым:
    иначе в список можно тихо дописать запись, легализующую переименование
    случая в обход доктрины.
    """

    for honest in _HONEST_SUFFIXES:
        for dishonest in _DISHONEST_SUFFIXES:
            assert not honest.endswith(dishonest), (honest, dishonest)
            assert not dishonest.endswith(honest), (honest, dishonest)
    known = _HONEST_SUFFIXES + _DISHONEST_SUFFIXES
    used = {
        suffix
        for case in CASES
        for suffix in known
        if case[0].endswith(suffix)
    }
    assert used == set(known), set(known) - used


# Честный случай обязан быть ДОСЛОВНЫМ куском своего источника — либо стоять
# здесь с письменным объяснением, почему недословный вывод всё-таки верен.
# Реестр пуст: все 19 честных случаев этой таблицы дословны.
_HONEST_NON_VERBATIM: dict[str, str] = {}


def _normalized(text: str) -> str:
    """Грубая нормализация для сверки дословности: регистр, ё, пунктуация."""

    lowered = text.lower().replace("\u0451", "\u0435")
    stripped = re.sub(r"[\u00ab\u00bb\u0022\u0027(),.:;!?\u2014\u2013-]+", " ", lowered)
    return re.sub(r"\s+", " ", stripped).strip()


def _honest_cases_are_verbatim_or_explained() -> None:
    """Честный случай обязан быть куском источника либо иметь объяснение.

    ЧЕТВЁРТЫЙ замок доктрины и единственный, который смотрит на СОДЕРЖИМОЕ, а
    не на литералы.  Первые три (выводимая из имени доктрина, счётчики по
    доктрине, отпечаток колонки) ловят подделку, пока подделыватель не правит
    всё сразу; этот ловит и того, кто правит всё: выдуманный вывод по
    построению не является дословным куском источника, и объявить его честным
    без письменной записи здесь нельзя.
    """

    known = {case[0] for case in CASES}
    assert set(_HONEST_NON_VERBATIM) <= known, set(_HONEST_NON_VERBATIM) - known
    for case_id, source, output, _expected, _measured, _note in CASES:
        if _doctrine_expected(case_id) != "PPPPP":
            assert case_id not in _HONEST_NON_VERBATIM, case_id
            continue
        if _normalized(output) in _normalized(source):
            assert case_id not in _HONEST_NON_VERBATIM, case_id
            continue
        reason = _HONEST_NON_VERBATIM.get(case_id)
        assert reason and reason.strip(), (
            f"{case_id}: вывод объявлен честным, но не является дословным "
            "куском источника и не объяснён в _HONEST_NON_VERBATIM"
        )


