_LEADERSHIP_DOC_BIAS = ["правил", "устав", "лидер", "организац", "наказ"]

# Подстроки названий документов, которые приоритезируем под роль (регистронезависимо).
RETRIEVAL_BIAS = {
    "advocate": ["процессуальн", "адвокат", "конституц", "уголовн", "административн"],
    "prosecutor": ["процессуальн", "прокур", "генеральн", "конституц", "полиц", "надзор"],
}


def normalize_mode(mode: Optional[str]) -> str:
    m = (mode or "general").strip().lower()
    return m if m in VALID_MODES else "general"


def get_role_prompt(mode: Optional[str], base_prompt: str) -> str:
    """Системный промпт под роль = персона роли + базовые правила. Для general — только база.
    Для leadership — ОТДЕЛЬНЫЙ краткий промпт (не базовый verbose-формат совета)."""
    m = normalize_mode(mode)
    if m == "leadership":
        return LEADERSHIP_SYSTEM_PROMPT          # самостоятельный, заменяет базу (краткий формат)
    persona = _PERSONA.get(m)
    return (persona + base_prompt) if persona else base_prompt


def retrieval_bias_terms(mode: Optional[str]) -> List[str]:
    m = normalize_mode(mode)
    if m == "leadership":
        return _LEADERSHIP_DOC_BIAS
    return RETRIEVAL_BIAS.get(m, [])


