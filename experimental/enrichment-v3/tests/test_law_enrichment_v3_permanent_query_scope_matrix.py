# Доктрина выводится из имени случая, а не пишется рядом с ним: суффикс имени
# говорит, честен вывод или нет, и самопроверка сверяет с ним колонку expected.
# Иначе колонка expected остаётся незащищённой и записанную дыру можно сделать
# зелёной правкой одной буквы.
_HONEST_SUFFIXES = (
    "-faithful",
    "-echo-control",
    "-verbatim",
    "-paraphrase",
)
_DISHONEST_SUFFIXES = (
    "-role-swap",
    "-actor-sub",
    "-patient-sub",
    "-recombination",
    "-invented-claim",
    "-invented-object",
    "-invented-actor",
    "-swapped-echo",
    "-to-assertion",
    "-swap",
)


def _doctrine_expected(case_id: str) -> str:
    """Пять букв, которых требует доктрина, по одному лишь имени случая."""

    honest = any(case_id.endswith(suffix) for suffix in _HONEST_SUFFIXES)
    dishonest = any(case_id.endswith(suffix) for suffix in _DISHONEST_SUFFIXES)
    if honest == dishonest:
        raise AssertionError(
            f"имя случая {case_id!r} не относит его ни к честным, ни к нечестным "
            f"выводам однозначно"
        )
    return "PPPPP" if honest else "RRRRR"


