# Колонка expected не пишется рядом со случаем — она ВЫВОДИТСЯ ИЗ ЕГО ИМЕНИ.
# Суффикс имени обязан попасть ровно в ОДИН из двух белых списков; имя, попавшее
# в оба списка или ни в один, роняет самопроверку.  Без этого записанную дыру
# можно закрасить правкой одной буквы в expected, и прибор молча подделается.
_HONEST_SUFFIXES = (
    "/exact",  # дословное эхо источника (или честная перестройка тех же ролей)
)
_DISHONEST_SUFFIXES = (
    "/actor-swap",  # актор подменён другим (в том числе взят у соседнего факта)
    "/actor-drop",  # роль актора усечена
    "/actor-add",  # к безакторному источнику дописан актор
    "/patient-swap",  # пациент подменён другим
    "/patient-add",  # дописан пациент, которого источник не несёт
    "/role-drop",  # усечена роль (актор или пациент) в SOV-раскладке
    "/polarity-swap",  # перевёрнута полярность
    "/modifier-swap",  # модификатор подменён другим
    "/invented-actor",  # актор, которого в источнике нет вовсе
    "/invented-term",  # выдуманный срок
    "/invented-money",  # выдуманная сумма
    "/invented-reference",  # выдуманная ссылка на статью
    "/invented-claim",  # утверждение целиком выдумано
)


def _doctrine_expected(case_id: str) -> str:
    """Пять букв, которых требует доктрина, по одному лишь имени случая."""

    honest = any(case_id.endswith(suffix) for suffix in _HONEST_SUFFIXES)
    dishonest = any(case_id.endswith(suffix) for suffix in _DISHONEST_SUFFIXES)
    if honest == dishonest:
        raise AssertionError(
            f"имя случая {case_id!r} не относит его ни к честным, ни к "
            "нечестным выводам однозначно: суффикс обязан попасть ровно в "
            "один из двух белых списков"
        )
    return "PPPPP" if honest else "RRRRR"


def _doctrine_white_lists_are_sound() -> None:
    """Белые списки обязаны быть взаимно однозначны и целиком рабочими.

    Ни один суффикс одного списка не смеет оканчиваться суффиксом другого —
    иначе имя попадёт сразу в оба.  И ни один суффикс не смеет быть мёртвым:
    иначе в список можно тихо дописать запись, легализующую переименование
    случая в обход доктрины.
    """

    for honest in _HONEST_SUFFIXES:
        for dishonest in _DISHONEST_SUFFIXES:
            assert not honest.endswith(dishonest), (honest, dishonest)
            assert not dishonest.endswith(honest), (honest, dishonest)
    known = _HONEST_SUFFIXES + _DISHONEST_SUFFIXES
    used = {
        suffix for case in CASES for suffix in known if case[0].endswith(suffix)
    }
    assert used == set(known), set(known) - used


