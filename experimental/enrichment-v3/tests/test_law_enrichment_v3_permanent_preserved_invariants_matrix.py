# Реестр закрытых волн: номер волны -> её словарь причин.  Новая волна заводит
# СВОЙ словарь и дописывает строку сюда.  Самопроверка ходит по этому реестру и
# требует от каждой записи трёх вещей: случай существует в таблице, его
# measured совпал с доктриной, а метка волны стоит и в причине, и в заметке
# случая — иначе закрытый дефект прочтётся как сегодняшнее поведение.
_CLOSED_HISTORY: tuple[tuple[int, dict[str, str]], ...] = (
    (7, CLOSED_BY_WAVE7),
    (9, CLOSED_BY_WAVE9),
)

_WAVE_MARK_RE = re.compile(r"волн\w*\s*(\d+)", re.IGNORECASE)


def _wave_marks(text: str) -> set[str]:
    """Номера волн, которые текст называет ЯВНО («закрыта волной 9»)."""

    return set(_WAVE_MARK_RE.findall(text))


# ЯКОРЯ КОРНЕЙ.  Причины ссылаются на АБСОЛЮТНЫЕ строки валидатора, а он растёт:
# волна 9 сдвинула его на сотни строк, и ссылка, которую никто не сверяет, тихо
# начинает указывать в чужой код — читатель верит цитате, которой там уже нет.
# Реестр привязывает каждую цитируемую строку к тексту, который обязан на ней
# стоять; мёртвая запись реестра запрещена так же, как мёртвый суффикс доктрины.
_ROOT_ANCHORS: dict[int, str] = {
    1193: "masked = _expand_word_numbers(masked)",
    3954: "def _relation_bounded_subject_proof_before_predicate(",
    13804: "def _strong_modal_action_slot_subject_proof(",
    50720: (
        "def _extract_qualitative_claims(value: str) -> "
        "set[_QualitativeClaim]:"
    ),
    60169: '"penalty evidence: output numeric fact "',
    60492: "def _validate_numeric_source_coverage(",
    61029: "_validate_numeric_source_coverage(",
    61264: "_validate_numeric_source_coverage(",
}

_ANCHOR_RE = re.compile(r"services/law_enrichment_validation\.py:(\d+)")


def _root_anchors_point_at_live_code() -> None:
    """Каждый корень «файл:строка» обязан указывать в ЖИВОЙ валидатор.

    Пятый замок.  Он ловит не подделку доктрины, а протухание доказательной
    базы: после правки валидатора номера строк съезжают, и причина начинает
    ссылаться на посторонний код, оставаясь по виду обоснованной.  Реестр
    сверяется в обе стороны — ни одна процитированная строка не смеет быть вне
    реестра, ни одна запись реестра не смеет быть непроцитированной.
    """

    source = Path(law_enrichment_validation.__file__).read_text(
        encoding="utf-8"
    )
    lines = source.split(chr(10))
    for line_no, text in sorted(_ROOT_ANCHORS.items()):
        assert 0 < line_no <= len(lines), (line_no, len(lines))
        assert lines[line_no - 1].strip() == text, (
            line_no,
            lines[line_no - 1].strip(),
            text,
        )
    cited: set[int] = set()
    for text in (
        __doc__ or "",
        *DIVERGENCE_REASONS.values(),
        *(reason for _, closed in _CLOSED_HISTORY for reason in closed.values()),
        *(case[5] for case in CASES),
    ):
        cited |= {int(number) for number in _ANCHOR_RE.findall(text)}
    assert cited == set(_ROOT_ANCHORS), (
        cited - set(_ROOT_ANCHORS),
        set(_ROOT_ANCHORS) - cited,
    )


def _divergence_reason(case_id: str) -> str:
    """Расхождение без описанного механизма и корня матрица не принимает."""

    reason = DIVERGENCE_REASONS.get(case_id)
    if reason is None:
        raise AssertionError(
            f"{case_id}: measured разошёлся с доктриной, но причина не "
            "описана в DIVERGENCE_REASONS — расхождение без механизма и "
            "корня «файл:строка» в матрицу не записывается"
        )
    return reason


def _matrix_params() -> tuple[object, ...]:
    params = []
    for case_id, source, output, expected, measured, _note in CASES:
        for index, path_id in enumerate(PATH_IDS):
            validate = ALL_OUTPUT_PATHS[index]
            expects_raise = expected[index] == "R"
            param_id = f"{case_id}-{path_id}"
            if measured[index] == expected[index]:
                params.append(
                    pytest.param(
                        validate,
                        source,
                        output,
                        expects_raise,
                        id=param_id,
                    )
                )
                continue
            params.append(
                pytest.param(
                    validate,
                    source,
                    output,
                    expects_raise,
                    id=param_id,
                    marks=pytest.mark.xfail(
                        strict=True,
                        reason=_divergence_reason(case_id),
                    ),
                )
            )
    return tuple(params)


@pytest.mark.parametrize(
    ("validate", "source", "output", "expects_raise"),
    _matrix_params(),
)
def test_v3_preserved_invariants_matrix_holds_on_every_output_path(
    validate: RelationValidator,
    source: str,
    output: str,
    expects_raise: bool,
) -> None:
    """Каждый случай класса обязан вести себя одинаково на своём пути."""

    if expects_raise:
        with pytest.raises(ValueError):
            validate(source, output)
        return
    validate(source, output)


# Ловушка обвязки: у обоих penalty-путей есть ПРЕДУСЛОВИЯ, и отказ на них
# выглядит как сработавший гейт, не будучи им.  Эти три сообщения — ровно такие
# отказы; ни одно из них не имеет права быть причиной R в матрице.
_PRECONDITION_BAILS = (
    "has no explicit sanction cue",
    "contains no source-backed category or fact",
    "is not a source-backed sanction",
)

# Закрытый реестр ячеек «случай -> путь», где буква R получена ОТКАЗОМ НА
# ПРЕДУСЛОВИИ, а не сработавшим гейтом.  Он ПУСТ — замер по всем 375 ячейкам R
# этой таблицы не нашёл ни одного предусловного отказа.  Шестнадцать ячеек,
# добавленных волной 9, замерены отдельно: все шестнадцать отказывают
# сообщением «output numeric fact ... is absent», то есть сработавшим гейтом.
# Тест ниже держит реестр с обеих сторон.
PRECONDITION_BAIL_CELLS: dict[str, tuple[str, ...]] = {}

# Отпечаток колонки expected (доктрина).  Строится по парам «id:expected», а не
# по счётчикам, поэтому правка ОДНОЙ буквы в любой строке ломает самопроверку.
# Менять его можно только вместе с осознанным изменением доктрины.
_EXPECTED_FINGERPRINT = (
    "81cc60b21c3b6aeb812ca76ef9030462e856b7777f2ab76b8fda7a813654f2cf"
)


def test_v3_preserved_invariants_no_r_letter_is_a_precondition_bail() -> None:
    """Ни одна буква R в таблице не смеет быть отказом на предусловии.

    Это та самая ловушка: у обоих penalty-путей есть предусловия, и отказ на
    них по одному лишь исходу неотличим от сработавшего гейта.  Проверка идёт
    по КАЖДОЙ ячейке R всей таблицы, а не по выборке из трёх случаев, и
    сверяет результат с закрытым реестром PRECONDITION_BAIL_CELLS в обе
    стороны: перечисленная ячейка обязана бейлиться, любая другая — обязана
    не бейлиться.
    """

    known = {case[0] for case in CASES}
    assert set(PRECONDITION_BAIL_CELLS) <= known

    checked = 0
    for case_id, source, output, _expected, measured, _note in CASES:
        registered = PRECONDITION_BAIL_CELLS.get(case_id, ())
        for index, path_id in enumerate(PATH_IDS):
            if measured[index] != "R":
                assert path_id not in registered, (case_id, path_id)
                continue
            checked += 1
            with pytest.raises(ValueError) as excinfo:
                ALL_OUTPUT_PATHS[index](source, output)
            message = str(excinfo.value)
            bailed = any(bail in message for bail in _PRECONDITION_BAILS)
            assert bailed == (path_id in registered), (case_id, path_id, message)
    # Столько букв R стоит в колонке measured; если таблица усохнет, проверка
    # не имеет права молча измельчать вместе с ней.  Волна 9 довела 16 ячеек
    # блока SF с P до R, и число выросло с 359 до 375 — пересчитано по таблице.
    assert checked == 375


def test_v3_preserved_invariants_matrix_bookkeeping() -> None:
    """Колонку expected нельзя ослабить правкой одной буквы.

    Пришпилено: состав таблицы, отпечаток доктрины, число дыр, число ложных
    блоков, число расхождений, соответствие расхождения записи в словаре
    причин, живость якорей корней и неизменность случаев, закрытых волнами 7
    и 9.
    """

    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5
    assert len({case[0] for case in CASES}) == len(CASES) == 98
    known = {case[0] for case in CASES}
    _doctrine_white_lists_are_sound()
    _honest_cases_are_verbatim_or_explained()
    _root_anchors_point_at_live_code()
    assert sum(1 for case in CASES if _doctrine_expected(case[0]) == "PPPPP") == 22
    assert sum(1 for case in CASES if _doctrine_expected(case[0]) == "RRRRR") == 76

    fingerprint = hashlib.sha256(
        "\n".join(f"{case[0]}:{case[3]}" for case in CASES).encode("utf-8")
    ).hexdigest()
    assert fingerprint == _EXPECTED_FINGERPRINT

    # Словари волн не сливаются и не пересекаются: один случай не может
    # числиться закрытым дважды, иначе по файлу нельзя прочесть, какая правка
    # что закрыла.
    closed_cases: set[str] = set()
    for wave, closed in _CLOSED_HISTORY:
        assert closed, wave
        assert not set(closed) & closed_cases, (wave, set(closed) & closed_cases)
        closed_cases |= set(closed)
    assert closed_cases <= known, closed_cases - known

    divergent: list[str] = []
    holes: list[str] = []
    false_blocks: list[str] = []
    for case_id, source, output, expected, measured, note in CASES:
        assert source and output, case_id
        assert note.strip(), case_id
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        # ГЛАВНАЯ защита: доктрину нельзя ослабить правкой буквы в expected —
        # она выводится из ИМЕНИ случая по двум белым спискам суффиксов.  Она
        # же одна на все пять путей: половинчатых строк доктрины не бывает.
        assert expected == _doctrine_expected(case_id), case_id
        assert expected in {"PPPPP", "RRRRR"}, case_id
        # Вердикт в заметке либо описывает ЖИВОЕ расхождение, либо случай
        # ЧИСЛИТСЯ в истории закрытых волн — иначе читатель примет закрытый
        # дефект за текущий.  Разряжает заметку именно ЗАПИСЬ в словаре
        # истории, а не слово «волна» в тексте: приписать слово дешевле, чем
        # завести запись, которую тут же проверяют остальные замки.
        if "ДЫРА" in note or "ЛОЖНЫЙ БЛОК" in note:
            assert (
                case_id in DIVERGENCE_REASONS or case_id in closed_cases
            ), case_id
        pairs = [index for index in range(5) if expected[index] != measured[index]]
        if not pairs:
            assert case_id not in DIVERGENCE_REASONS, case_id
            continue
        divergent.extend(f"{case_id}-{PATH_IDS[index]}" for index in pairs)
        assert case_id in DIVERGENCE_REASONS, case_id
        if any(measured[index] == "P" for index in pairs):
            holes.append(case_id)
        else:
            false_blocks.append(case_id)

    # Волна 7 закрыла СВОЙ класс целиком: среди 86 случаев трёх исходных блоков
    # расхождений нет ни одного.  Волна 9 закрыла в блоке sanction facet четыре
    # случая из пяти — 16 пар из 21.  Живым осталось ОДНО расхождение, SF-06, и
    # это ДЫРА; ложных блоков в таблице нет ни одного.
    assert len(holes) == 1
    assert len(false_blocks) == 0
    assert len(divergent) == 5
    assert set(DIVERGENCE_REASONS) == set(holes) | set(false_blocks)
    assert not [case for case in CASES[:86] if case[0] in DIVERGENCE_REASONS]

    assert len(CLOSED_BY_WAVE7) == 9
    assert len(CLOSED_BY_WAVE9) == 4
    # ИСТОРИЯ САМА РАБОТАЕТ СТОРОЖЕМ.  Закрытый случай обязан ОСТАВАТЬСЯ
    # сошедшимся с доктриной: его причина лежит в истории, а в живом словаре её
    # нет, поэтому повторное открытие дыры не уйдёт в тихий xfail — оно уронит
    # и эту проверку, и сбор матрицы.
    assert not closed_cases & set(DIVERGENCE_REASONS)
    by_id = {case[0]: case for case in CASES}
    # Причина обязана называть корень «файл:строка», а историческая — ещё и
    # НОМЕР волны, которой дефект закрыт, причём и в причине, и в заметке
    # случая: без этого пояснительный слой снова начнёт читаться как описание
    # СЕГОДНЯШНЕГО поведения.
    for reason_id, reason in DIVERGENCE_REASONS.items():
        assert "services/law_enrichment_validation.py:" in reason, reason_id
    for wave, closed in _CLOSED_HISTORY:
        for case_id, reason in closed.items():
            assert "services/law_enrichment_validation.py:" in reason, case_id
            assert str(wave) in _wave_marks(reason), (case_id, reason)
            _cid, _source, _output, expected, measured, note = by_id[case_id]
            assert expected == measured, case_id
            assert str(wave) in _wave_marks(note), (case_id, note)


def test_v3_preserved_invariants_penalty_harness_reaches_relation_gate() -> None:
    """Оба penalty-пути обязаны доходить до разбора отношения, а не до предусловия.

    Контрольная тройка носителя: дословный вывод — PPPPP, подмена пациента —
    RRRRR, подмена актора — RRRRR; при этом ни один отказ не имеет права быть
    отказом на предусловии, иначе оба R были бы ложными.
    """

    by_id = {case[0]: case for case in CASES}
    penalty_paths = (_validate_penalty_summary, _validate_penalty_other)

    _cid, source, output, expected, measured, _note = by_id["ES-01-faithful"]
    assert expected == measured == "PPPPP"
    for validate in penalty_paths:
        validate(source, output)

    # ES-05-borrowed-patient — подмена пациента, ES-04-borrowed-actor — подмена актора на том же носителе.
    for case_id in ("ES-05-borrowed-patient", "ES-04-borrowed-actor"):
        _cid, source, output, expected, measured, _note = by_id[case_id]
        assert expected == measured == "RRRRR"
        for validate in penalty_paths:
            with pytest.raises(ValueError) as excinfo:
                validate(source, output)
            message = str(excinfo.value)
            for bail in _PRECONDITION_BAILS:
                assert bail not in message, f"{case_id}: {message}"
