# 5. SINGLE DOCUMENT VULNERABILITY (CORE, drop-in) — апгрейд мышления
# ===========================================================================
# РАЗБОР:
#   - Та же выходная схема (совместимость с validate_findings), но мышление
#     целеориентированное: «чего добивается актор и как этот документ ему
#     помогает», + установка собирать мини-цепочки даже внутри одного закона.
#   - abuse_scenarios просим давать как ПОШАГОВЫЙ сценарий, а не одну фразу.

def get_single_document_loophole_prompt(document_title: str, analysis_type: str) -> str:
    return f"""Ты разбираешь один внутриигровой закон RP-сервера и ищешь, как им можно вредить.

Документ: {document_title}
Тип анализа: {analysis_type}

Думай как актор с целью, а не как проверяющий по списку. Прокрути в голове: чего хочет добиться силовик-абузер (задавить, изъять, задержать, не вернуть) и чего — прокурор (натянуть состав); как адвокат развалит результат; что это делает с балансом. Даже в одном документе ищи МИНИ-СВЯЗКИ (норма + пропущенный срок + перекос доказывания дают необратимый результат), а не только одиночные дефекты. Бери только то, что обосновано текстом ЭТОГО документа.

Для каждой находки заполни:
- title — суть схемы, а не название дефекта;
- vulnerability_type — из перечня ниже;
- source_documents — ["{document_title}"];
- source_fragments — дословные цитаты, на которых держится схема;
- issue_summary — в чём дыра и почему она рабочая;
- abuse_scenarios — ПОШАГОВО, как актор это разыгрывает (шаг 1 → шаг 2 → результат), и переживёт ли это жалобу;
- affected_roles — кого бьёт и кто выигрывает;
- gameplay_impact — как ломает игру;
- severity / confidence;
- fix_recommendation — минимальная правка текста, закрывающая схему.

Перед уверенным выводом мысленно сыграй за адвоката: если схема рассыпается без натяжки — снизь confidence и скажи почему.

Верни JSON строго в формате:
{{
  "document_title": "...",
  "findings": [
    {{
      "title": "...",
      "vulnerability_type": "direct_contradiction|regulatory_gap|narrow_wording|vague_term|missing_procedure|missing_sanction|sanction_without_offense|authority_collision|hierarchy_unclear|missing_deadline|overbroad_exception|missing_subject|missing_object|double_punishment|proof_impossibility|other",
      "source_documents": ["..."],
      "source_fragments": ["..."],
      "issue_summary": "...",
      "abuse_scenarios": ["..."],
      "affected_roles": ["..."],
      "gameplay_impact": "...",
      "severity": "low|medium|high|critical",
      "confidence": "low|medium|high",
      "fix_recommendation": "..."
    }}
  ],
  "analysis_limits": ["..."]
}}

Текста вне JSON не добавляй. Нет уязвимостей — верни пустой findings. Фрагменты не выдумывай."""


# ===========================================================================
# 6. CROSS DOCUMENT CONTRADICTION (CORE, drop-in) — апгрейд на цепочки
# ===========================================================================
# РАЗБОР:
#   - Это самый ценный проход для «человеческого» мышления: именно на стыке
#     документов рождаются настоящие схемы. Просим строить эксплойт-цепочки,
#     где звенья — из РАЗНЫХ документов, и перечислять ВСЕ источники звеньев.
#   - Схема совместима: цепочка = одна finding с несколькими source_documents
#     и несколькими source_fragments; шаги — в abuse_scenarios.

def get_cross_document_contradiction_prompt(analysis_type: str, grouped_context: str) -> str:
    return f"""Ты собираешь абуз-схемы на СТЫКЕ нескольких внутриигровых законов RP-сервера. Здесь живёт самое опасное: то, что в одном документе выглядит безобидно, в связке с другим даёт необратимый результат.

Тип анализа: {analysis_type}

Контекст норм:
{grouped_context}

Работай как человек, который хочет добиться результата:
1. Возьми цель актора (например: силовик хочет легально изъять бизнес конкурента и не отдать назад; или: игрок хочет спровоцировать конфликт и уйти от наказания).
2. Прострой ПУТЬ к цели как цепочку звеньев из РАЗНЫХ документов: что открывает дверь → что убирает препятствие → что даёт время → что делает результат необратимым → куда денется жалоба.
3. Проверь связку «адвокатом»: где она рвётся, как её залатать актору, насколько устойчива.

Ищи в том числе: прямые противоречия (один разрешает — другой запрещает); конфликт процедур и полномочий; неясную иерархию; разные сроки/наказания за одно; двойную квалификацию; ситуацию «один закон требует действие, другой делает его невозможным»; общее право гражданина против специального полномочия.

Каждую схему оформляй как одну находку, где source_documents и source_fragments перечисляют ВСЕ звенья цепочки, а abuse_scenarios — пошаговый разбор пути к цели.

Верни JSON строго в формате:
{{
  "findings": [
    {{
      "title": "...",
      "vulnerability_type": "direct_contradiction|procedure_conflict|authority_collision|hierarchy_unclear|deadline_conflict|sanction_conflict|double_punishment|rights_vs_power_conflict|regulatory_gap|proof_impossibility|other",
      "source_documents": ["...", "..."],
      "source_fragments": ["...", "..."],
      "issue_summary": "...",
      "abuse_scenarios": ["шаг 1 ...", "шаг 2 ...", "результат ..."],
      "affected_roles": ["..."],
      "gameplay_impact": "...",
      "severity": "low|medium|high|critical",
      "confidence": "low|medium|high",
      "fix_recommendation": "..."
    }}
  ],
  "analysis_limits": ["..."]
}}

Текста вне JSON не добавляй. Не называй противоречием то, что спокойно согласуется без правки текста. Если связка держится на слабом предположении — confidence="low". Источники не выдумывай."""


