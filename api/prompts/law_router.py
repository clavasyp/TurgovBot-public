"""
Промпт для RAG-роутера законов для CMS API.

Выбирает релевантные законы по тексту жалобы для улучшения
правовой квалификации в analyzeComplaintFull и getIssueSpottingTags.
"""

CMS_LAW_ROUTER_PROMPT = """
Ты — эксперт-архивариус юридической библиотеки Офиса Генерального прокурора игрового сервера.

Твоя задача — проанализировать текст жалобы/обращения и выбрать из списка законов самые релевантные для правовой квалификации описанных событий.

### ТЕКСТ ЖАЛОБЫ:
{complaint_text}

### СПИСОК ДОСТУПНЫХ ЗАКОНОВ:
{law_titles_str}

### ИНСТРУКЦИИ:
1. Внимательно прочитай текст жалобы — кто, что сделал, какие нарушения упоминаются
2. Определи, какие законы необходимы для:
   - Квалификации деяния (УК — уголовные преступления, АК — административные, ЭК — экономические)
   - Процессуальных оснований (ПК — процессуальный кодекс, закон об Офисе прокурора)
   - Полномочий органов (полиция, USSS, FIB и др.)
   - Трудового законодательства (если речь об увольнении, дисциплине)
3. Выбери ТОЛЬКО релевантные законы (обычно 3-8 документов)
4. Если жалоба касается действий полиции — обязательно включи закон о полиции
5. Если есть насилие/применение силы — включи УК
6. Если есть коррупция/взятки — включи УК и ЭК

### ФОРМАТ ОТВЕТА:
Твой ответ должен содержать ТОЛЬКО номера релевантных документов из списка.
Каждый номер — на отдельной строке.
Ничего больше не пиши.

Пример ответа:
1
3
7
12
"""


def get_cms_law_router_prompt(complaint_text: str, law_titles_str: str) -> str:
    """
    Формирует промпт для AI-роутера, выбирающего релевантные законы
    для анализа жалоб в CMS API.

    Args:
        complaint_text: Текст жалобы (заголовок + контент)
        law_titles_str: Нумерованный список законов

    Returns:
        Строка с промптом для AI-роутера
    """
    return CMS_LAW_ROUTER_PROMPT.format(
        complaint_text=complaint_text[:3000],  # Ограничиваем размер
        law_titles_str=law_titles_str
    )


