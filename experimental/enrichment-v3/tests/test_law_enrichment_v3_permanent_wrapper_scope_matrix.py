# СТОРОЖ САМОЙ ТАБЛИЦЫ.
#
# Колонка measured подделке не поддаётся: расхождение с реальностью даёт либо
# обычное падение зелёной строки, либо XPASS(strict).  Незащищённой в этой
# матрице оставалась ровно колонка expected, то есть ДОКТРИНА: правкой двух
# строковых литералов записанная дыра превращалась в зелёный тест, и ничто в
# дереве не падало.  Ниже доктрина выводится МАШИННО из source/output.
#
# Правило доктрины: вывод честен тогда и только тогда, когда он дословный
# фрагмент источника — с точностью до схлопывания пробельных символов и до
# ОТБРОШЕННОГО имени, взятого в полную обёртку.  Перекомбинация пациента,
# перекомбинация актора и выдуманный токен честными не являются никогда.
#
# Список обёрток ниже НАМЕРЕННО шире инвентаря валидатора (в нём есть и
# фигурные скобки, и бэктик, и **звёздочки**, которые валидатор обёрткой не
# считает) — иначе доктрина унаследовала бы ровно ту дыру, которую обязана
# мерить.  Проверено: и на узком инвентаре валидатора, и на этом широком
# списке колонка expected получается одна и та же для всех случаев таблицы.
_DOCTRINE_SPACE_RE = re.compile("[\\s\\u00a0\\u202f\\u200b\\u200c\\ufeff]+")
_DOCTRINE_NAME_WRAPPERS: tuple[tuple[str, str], ...] = (
    ("«", "»"), ("“", "”"), ("„", "“"),
    ("‹", "›"), ("(", ")"), ("[", "]"), ('"', '"'), ("'", "'"),
    ("‘", "’"), ("{", "}"), ("<", ">"), ("「", "」"),
    ("【", "】"), ("⟨", "⟩"), ("〈", "〉"),
    ("｢", "｣"), ("❨", "❩"), ("（", "）"),
    ("［", "］"), ("＂", "＂"), ("‚", "’"),
    ("’", "’"), ("”", "”"), ("»", "«"),
    ("‛", "’"), ("‘", "‘"), ("„", "”"),
    ("ʼ", "ʼ"), ("_", "_"), ("`", "`"), ("**", "**"),
    ("--", "--"), ("/", "/"), ("|", "|"), ("′", "′"),
    ("—", "—"), ("~~", "~~"),
)


def _doctrine_squeeze(text: str) -> str:
    return _DOCTRINE_SPACE_RE.sub(" ", text).strip()


def _doctrine_drop_wrapped_names(text: str) -> str:
    """Убрать из ИСТОЧНИКА целиком сбалансированные обёртки-имена."""

    surface = text
    for opener, closer in _DOCTRINE_NAME_WRAPPERS:
        pattern = (
            re.escape(opener)
            + "[^"
            + re.escape(opener + closer)
            + "]{0,40}"
            + re.escape(closer)
        )
        surface = re.sub(pattern, " ", surface)
    return surface


def _doctrine_expectation(source: str, output: str) -> str:
    """Пять букв доктрины, посчитанные без единого обращения к валидатору."""

    candidate = _doctrine_squeeze(output).rstrip(".").strip()
    if not candidate:
        return "RRRRR"
    if candidate in _doctrine_squeeze(source):
        return "PPPPP"
    if candidate in _doctrine_squeeze(_doctrine_drop_wrapped_names(source)):
        return "PPPPP"
    return "RRRRR"


