"""
Доменный словарь для адаптации распознавания речи (PhraseSet для chirp_3).

Поднимает точность на юридическом RP-домене: названия кодексов, процессуальные термины,
структура норм («статья», «часть», «пункт»), органы и их аббревиатуры, сленг задержаний.
Лечит типичные ошибки STT на разговорной речи (напр. «заканфул», обрезанные термины).

Подключается по умолчанию в services/stt_service.stream_transcribe (если phrases не переданы).
boost задаётся в stt_service (≈12). Можно расширять per-role/per-server позже.
"""

from __future__ import annotations

from typing import List, Optional

# Кодексы и базовые источники норм
_CODES = [
    "Процессуальный кодекс", "Уголовный кодекс", "Административный кодекс",
    "Дорожный кодекс", "Трудовой кодекс", "Судебный кодекс", "Этический кодекс",
    "Конституция", "Закон об адвокатуре", "Закон о прокуратуре", "Закон о полиции",
]

# Структура норм (помогает связать «статья 17 часть 2 пункт б»)
_STRUCTURE = ["статья", "часть", "пункт", "глава", "раздел", "абзац"]

# Процессуальные термины
_PROCEDURE = [
    "задержание", "задержанный", "арест", "обыск", "личный досмотр", "досмотр",
    "основания задержания", "протокол", "понятой", "права задержанного",
    "правило Миранды", "право на адвоката", "право хранить молчание",
    "видеозапись", "видеофиксация", "срок задержания", "мера пресечения",
    "освобождение", "недопустимое доказательство", "недопустимость доказательств",
    "ходатайство", "жалоба", "апелляция", "обвинение", "защита", "квалификация",
    "надзор", "прокурорская проверка", "прокурорский надзор", "обвинительное заключение",
    "процессуальное нарушение", "правонарушение", "состав преступления", "санкция",
    "юрисдикция", "доказательство", "улика", "свидетель", "подозреваемый",
]

# Роли и органы
_ROLES = [
    "адвокат", "прокурор", "прокуратура", "судья", "суд", "сотрудник", "офицер",
    "государственный служащий", "госслужащий", "начальник отдела", "коллегия адвокатов",
]

# Аббревиатуры органов (gta5rp / Majestic и общие)
_ORGS = [
    "ЛСПД", "LSPD", "ФИБ", "FIB", "ЕМС", "EMS", "СОБР", "ДПС", "ГИБДД", "КПЗ",
    "УВД", "ДОС", "Минюст", "Нацгвардия", "САНГ", "УССС", "Визл Ньюс",
]

# Базовый словарь (server-agnostic)
_BASE: List[str] = _CODES + _STRUCTURE + _PROCEDURE + _ROLES + _ORGS

# Уклон под роль (добавки к базовому)
_BY_MODE = {
    "advocate": ["защитник", "линия защиты", "смягчающие обстоятельства", "незаконное задержание"],
    "prosecutor": ["надзорное производство", "обязательное указание", "отстранение", "инспекция"],
}


def default_phrases(mode: Optional[str] = None) -> List[str]:
    """Курируемый словарь фраз для адаптации STT (опц. с уклоном под роль)."""
    extra = _BY_MODE.get((mode or "").strip().lower(), [])
    # dedupe с сохранением порядка, лимит 1000 (ограничение inline PhraseSet)
    seen = set()
    out: List[str] = []
    for p in _BASE + extra:
        if p not in seen:
            seen.add(p)
            out.append(p)
    return out[:1000]


