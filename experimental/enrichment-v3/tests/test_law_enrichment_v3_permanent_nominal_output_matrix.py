# Составные предлоги, которые обязаны исчезнуть до разбора на слова.
_DOCTRINE_COMPOUND_PREPOSITIONS = ("со стороны", "в отношении")

_DOCTRINE_TOKEN_RE = re.compile(r"[а-яa-z]+|\d+(?:[.,]\d+)*")
_DOCTRINE_SENTENCE_RE = re.compile(r"(?<=[.!?])\s+")


def _doctrine_normalize(text: str) -> str:
    surface = text.lower().replace("ё", "е")
    for compound in _DOCTRINE_COMPOUND_PREPOSITIONS:
        surface = surface.replace(compound, " ")
    return surface


def _doctrine_lemma(token: str) -> str:
    for prefix, lemma in _DOCTRINE_STEMS_SORTED:
        if token.startswith(prefix):
            return lemma
    return token


def _doctrine_lemmas(text: str) -> frozenset[str]:
    lemmas = set()
    for token in _DOCTRINE_TOKEN_RE.findall(_doctrine_normalize(text)):
        if token in _DOCTRINE_FUNCTION_WORDS or token in _DOCTRINE_SCAFFOLD:
            continue
        lemmas.add(_doctrine_lemma(token))
    return frozenset(lemmas)


def _doctrine_facts(source: str) -> tuple[frozenset[str], ...]:
    return tuple(
        _doctrine_lemmas(sentence)
        for sentence in _DOCTRINE_SENTENCE_RE.split(source.strip())
        if sentence.strip()
    )


def _doctrine_expectation(source: str, output: str) -> str:
    """Пять букв доктрины, посчитанные без единого обращения к валидатору."""

    claimed = _doctrine_lemmas(output)
    if not claimed:
        return "RRRRR"
    for fact in _doctrine_facts(source):
        if claimed <= fact:
            return "PPPPP"
    return "RRRRR"


