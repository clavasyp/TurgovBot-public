def _matrix_params() -> tuple[object, ...]:
    params = []
    for case_id, source, output, expected, measured, _note in CASES:
        for index, path_id in enumerate(PATH_IDS):
            marks: tuple[object, ...] = ()
            if measured[index] != expected[index]:
                kind = "ДЫРА" if expected[index] == "R" else "ЛОЖНЫЙ БЛОК"
                marks = (
                    pytest.mark.xfail(
                        strict=True,
                        reason=f"{kind}: {DIVERGENCE_MECHANISM[case_id]}",
                    ),
                )
            params.append(
                pytest.param(
                    ALL_OUTPUT_PATHS[index],
                    source,
                    output,
                    expected[index],
                    id=f"{case_id}-{path_id}",
                    marks=marks,
                )
            )
    return tuple(params)


@pytest.mark.parametrize(
    ("validate", "source", "output", "doctrine"),
    _matrix_params(),
)
def test_nominal_output_evidence_gates(
    validate: RelationValidator,
    source: str,
    output: str,
    doctrine: str,
) -> None:
    if doctrine == "R":
        with pytest.raises(ValueError):
            validate(source, output)
    else:
        validate(source, output)


