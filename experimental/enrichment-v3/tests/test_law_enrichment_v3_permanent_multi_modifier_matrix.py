def _divergence_reason(case_id: str) -> str:
    """Расхождение без описанного механизма и корня матрица не принимает."""

    reason = DIVERGENCE_REASONS.get(case_id)
    if reason is None:
        raise AssertionError(
            f"{case_id}: measured разошёлся с доктриной, но причина не "
            "описана в DIVERGENCE_REASONS — расхождение без механизма и "
            "корня «файл:строка» в матрицу не записывается"
        )
    return reason


def _matrix_params() -> tuple[object, ...]:
    params: list[object] = []
    for case_id, source, output, expected, measured, _note in CASES:
        for index, path_id in enumerate(PATH_IDS):
            wanted = expected[index]
            marks: tuple[object, ...] = ()
            if measured[index] != wanted:
                marks = (
                    pytest.mark.xfail(
                        strict=True,
                        reason=_divergence_reason(case_id),
                    ),
                )
            params.append(
                pytest.param(
                    ALL_OUTPUT_PATHS[index],
                    source,
                    output,
                    wanted,
                    id=f"{case_id}-{path_id}",
                    marks=marks,
                )
            )
    return tuple(params)


