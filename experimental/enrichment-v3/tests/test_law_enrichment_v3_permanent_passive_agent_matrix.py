def _matrix_params() -> tuple[object, ...]:
    params: list[object] = []
    for case_id, source, output, expected, measured, _note in CASES:
        for index, path_id in enumerate(PATH_IDS):
            validate = ALL_OUTPUT_PATHS[index]
            expects_raise = expected[index] == "R"
            param_id = f"{case_id}-{path_id}"
            marks: tuple[object, ...] = ()
            if measured[index] != expected[index]:
                marks = (
                    pytest.mark.xfail(
                        strict=True,
                        reason=XFAIL_REASONS[case_id],
                    ),
                )
            params.append(
                pytest.param(
                    source,
                    output,
                    expects_raise,
                    validate,
                    id=param_id,
                    marks=marks,
                )
            )
    return tuple(params)


@pytest.mark.parametrize(
    ("source", "output", "expects_raise", "validate"),
    _matrix_params(),
)
def test_v3_passive_agent_permanent_matrix(
    source: str,
    output: str,
    expects_raise: bool,
    validate: RelationValidator,
) -> None:
    if expects_raise:
        with pytest.raises(ValueError):
            validate(source, output)
        return
    validate(source, output)


def test_v3_passive_agent_matrix_bookkeeping() -> None:
    """Прибор сторожит сам себя: доктрину, пояснения и счётчики.

    Проверяется четыре вещи, которых поодиночке нет ни в одной прежней
    матрице:

    1. колонка ``expected`` выводится из id МЕХАНИЧЕСКИ, и сам id проверяется
       по тексту — «-literal» обязан быть непрерывной подстрокой источника, а
       любой другой случай обязан ею не быть, поэтому ослабить доктрину
       правкой двух литералов нельзя;
    2. порядок колонок привязан к именам функций-путей, поэтому перестановка
       ``ALL_OUTPUT_PATHS`` не сдвинет молча смысл букв;
    3. пояснительный слой (``note``) связан с ``measured``: слово «ДЫРА»
       допустимо только там, где реально течёт, «ЛОЖНЫЙ БЛОК» — только там,
       где реально режет, иначе текст начнёт описывать несуществующий мир;
       единственное исключение — случай, ЗАКРЫТЫЙ волной: он сохраняет в
       заметке историю дефекта, но платит за это тремя условиями (см. п. 10);
    4. контрольная тройка носителя записана в таблицу и сверяется здесь, а
       носители с зарезанным дословным выводом перечислены явно.

    Волна 9 добавила ещё пять, и все пять - против правки таблицы, а не
    против правки валидатора:

    5. носитель без единой подмены ничего не меряет, поэтому такие носители
       перечислены поимённо;
    6. одна пара (источник, вывод) не может стоять в таблице с двумя
       вердиктами - замер обязан быть непротиворечив;
    7. восемь групп, где ОДНА строка вывода получает оба исхода в разных
       источниках: это машинная запись того, что решает источник, а не
       вывод, и подровнять буквы, не сломав её, нельзя;
    8. у каждого нового текущего носителя тройка «дословный проходит -
       подмена режется - течёт заявленное» сверяется поимённо;
    9. каждая координата корня сверяется с ЖИВЫМ файлом валидатора: волна 8
       сдвинула его на сотни строк, и прежние ссылки указывали в пустоту;
       волна 9 завела под якорь и координаты модульной докстроки.

    Волна 9 добавила десятый пункт — книги истории:

    10. закрытый случай не выпадает из-под сторожа, а переходит под другой,
        более строгий: его причина остаётся в книге своей волны, книга
        обязана нести МЕТКУ волны прямо в тексте причины, род сохранённой
        истории обязан совпасть со словом в заметке, а сам случай обязан
        БОЛЬШЕ НЕ РАСХОДИТЬСЯ с доктриной.  Поэтому повторное открытие
        закрытой дыры валит матрицу здесь же, а «закрыть» неудобный случай
        припиской id в словарь нельзя: без причины с меткой волны и без
        сошедшихся букв самопроверка не примет.
    """

    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5
    for path_id, validate in zip(PATH_IDS, ALL_OUTPUT_PATHS):
        assert validate.__name__ == "_validate_" + path_id.replace("-", "_")

    ids = [case[0] for case in CASES]
    assert len(set(ids)) == len(ids) == 193

    # (10) книги истории: id -> (метка волны, причина).  Одна и та же
    # запись не может лежать в двух волнах, а закрывать можно только то,
    # что в таблице есть.
    closed_history: dict[str, tuple[str, str]] = {}
    for mark, book in CLOSED_HISTORY_BOOKS:
        for closed_id, closed_reason in book.items():
            assert closed_id not in closed_history, closed_id
            closed_history[closed_id] = (mark, closed_reason)
    assert set(closed_history) <= set(ids), set(closed_history) - set(ids)

    holes: list[str] = []
    false_blocks: list[str] = []
    divergent: list[str] = []
    literal_by_source: dict[str, list[str]] = {}
    for case_id, source, output, expected, measured, note in CASES:
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        assert source.endswith("."), case_id
        assert note.strip(), case_id

        # (1) доктрина из id + проверка самого id по тексту.
        verbatim = case_id.endswith("-literal")
        assert (output in source) is verbatim, case_id
        assert expected == ("PPPPP" if verbatim else "RRRRR"), case_id
        literal_by_source.setdefault(source, [])
        if verbatim:
            literal_by_source[source].append(case_id)

        pairs = [
            index for index in range(5) if expected[index] != measured[index]
        ]
        leaks = [index for index in pairs if measured[index] == "P"]
        blocks = [index for index in pairs if measured[index] == "R"]
        # Один случай не может одновременно течь и ложно резать: доктрина у
        # него одна на все пять путей.
        assert not (leaks and blocks), case_id

        # (3) пояснение обязано следовать замеру.
        history = closed_history.get(case_id)
        if history is None:
            assert ("ДЫРА" in note) is bool(leaks), case_id
            assert ("ЛОЖНЫЙ БЛОК" in note) is bool(blocks), case_id
        else:
            # (10) Закрытый случай сохраняет в заметке ИСТОРИЮ дефекта — она
            # и есть доказательная база следующего ревью, — поэтому слова
            # «ДЫРА» и «ЛОЖНЫЙ БЛОК» в ней допустимы.  Но не даром:
            mark, closed_reason = history
            # (а) закрытый случай обязан БОЛЬШЕ НЕ расходиться с доктриной —
            #     повторное открытие дыры валит матрицу прямо здесь;
            assert expected == measured, case_id
            # (б) причина обязана нести метку своей волны, род дефекта и
            #     ссылку на корень: молчаливой «закрывающей» приписки id в
            #     словарь не хватит;
            was_hole = closed_reason.startswith(f"{mark}. ДЫРА: ")
            was_block = closed_reason.startswith(f"{mark}. ЛОЖНЫЙ БЛОК: ")
            assert was_hole != was_block, case_id
            assert _VALIDATOR_MODULE in closed_reason, case_id
            # (в) слово в заметке обязано совпасть с РОДОМ сохранённой
            #     истории: у закрытой дыры — «ДЫРА», у закрытого ложного
            #     блока — «ЛОЖНЫЙ БЛОК», и никогда наоборот.
            assert ("ДЫРА" in note) is was_hole, case_id
            assert ("ЛОЖНЫЙ БЛОК" in note) is was_block, case_id

        if not pairs:
            assert case_id not in XFAIL_REASONS, case_id
            continue
        divergent.extend(f"{case_id}-{PATH_IDS[index]}" for index in pairs)
        assert case_id in XFAIL_REASONS, case_id
        reason = XFAIL_REASONS[case_id]
        assert reason.startswith(
            "ДЫРА: " if leaks else "ЛОЖНЫЙ БЛОК: "
        ), case_id
        assert _VALIDATOR_MODULE in reason, case_id
        (holes if leaks else false_blocks).append(case_id)

    assert set(XFAIL_REASONS) == set(holes) | set(false_blocks)
    # Книги истории закрыты по счёту, не сливаются и не пересекаются с
    # текущими расхождениями: случай либо ещё течёт, либо уже закрыт.
    assert len(CLOSED_BY_WAVE8) == 21
    assert len(CLOSED_BY_WAVE9) == 2
    assert len(closed_history) == 23
    assert not set(closed_history) & set(XFAIL_REASONS)
    # Волна 9 закрыла 34 пары: 10 случаев, из них два (TIN06-fine-literal и
    # TIR05-fine-literal) целиком — они и уехали в CLOSED_BY_WAVE9, — а
    # восемь ложных блоков сузились с пяти путей до двух penalty-ног.
