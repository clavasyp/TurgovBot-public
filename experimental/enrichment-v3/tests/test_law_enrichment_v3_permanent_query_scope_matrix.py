RelationValidator = Callable[[str, str], None]


def _validate_title(source: str, output: str) -> None:
    validate_enrichment_title_source_evidence(
        source,
        output,
        source_title=None,
    )


def _validate_single_synonym(source: str, output: str) -> None:
    validate_synonym_source_evidence(source, [output])


def _validate_full_set(source: str, output: str) -> None:
    source_surface = source.rstrip(".")
    validate_synonym_source_evidence(
        source,
        [source_surface, output]
        if output != source_surface
        else [source_surface],
    )


# Обвязка penalty-путей. Без префикса "Наказание: " источник не несёт явного
# признака санкции и оба penalty-пути падают на предусловии
# "target article has no explicit sanction cue" — то есть были бы «зелёными» по
# ложной причине. Носители подобраны так, чтобы санкционная категория сидела
# внутри самой роле-несущей клаузы: иначе вывод падает на "output sanction text
# ... contains no source-backed category or fact". Живость обвязки на КАЖДОМ
# носителе доказана контрольной тройкой, см. PENALTY_LIVENESS_CONTROLS.
def _validate_penalty_summary(source: str, output: str) -> None:
    validate_penalty_source_evidence("Наказание: " + source, output, None)


def _validate_penalty_other(source: str, output: str) -> None:
    validate_penalty_source_evidence(
        "Наказание: " + source,
        None,
        {"other": output},
    )


