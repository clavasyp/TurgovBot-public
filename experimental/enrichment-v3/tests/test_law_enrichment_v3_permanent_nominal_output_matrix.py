def test_nominal_matrix_bookkeeping() -> None:
    """Таблица не должна разъезжаться ни с замером, ни с доктриной."""

    assert len(ALL_OUTPUT_PATHS) == len(PATH_IDS) == 5

    # 1. доктрина обязана оставаться различающей, а не константой
    assert _doctrine_expectation(
        "Организация налагает арест. Комиссия налагает штраф.",
        "Наложение ареста организацией",
    ) == "PPPPP"
    assert _doctrine_expectation(
        "Организация налагает арест. Комиссия налагает штраф.",
        "Наложение ареста комиссией",
    ) == "RRRRR"
    assert _doctrine_expectation(
        "Организация налагает арест. Комиссия налагает штраф.",
        "Наложение штрафа организацией",
    ) == "RRRRR"
    assert _doctrine_expectation(
        "Организация налагает арест. Комиссия налагает штраф.",
        "Наложение ареста организацией по статье 99.1",
    ) == "RRRRR"
    assert _doctrine_expectation(
        "Организация налагает арест. Комиссия налагает штраф.",
        "Запрет на наложение ареста организацией",
    ) == "RRRRR"
    # именная и глагольная формы одного факта обязаны сходиться
    assert _doctrine_lemmas("Комиссия налагает штраф") == _doctrine_lemmas(
        "Наложение штрафа комиссией"
    )
    # леса и предлоги не имеют права нести факт: ни одно их слово не должно
    # попадать ни в одну основу таблицы
    assert not _DOCTRINE_SCAFFOLD & _DOCTRINE_FUNCTION_WORDS
    for word in _DOCTRINE_SCAFFOLD | _DOCTRINE_FUNCTION_WORDS:
        assert _doctrine_lemma(word) == word, word
    assert _doctrine_lemmas("Организация осуществляет наложение ареста") == (
        _doctrine_lemmas("Организация налагает арест")
    )

    # 2. форма таблицы и МАШИННО выведенная колонка expected
    case_ids = [case[0] for case in CASES]
    assert len(set(case_ids)) == len(case_ids) == 137

    holes: set[str] = set()
    false_blocks: set[str] = set()
    divergent_params: list[str] = []
    for case_id, source, output, expected, measured, note in CASES:
        assert len(expected) == len(measured) == 5, case_id
        assert set(expected) <= {"P", "R"}, case_id
        assert set(measured) <= {"P", "R"}, case_id
        assert source and output and note.strip(), case_id
        assert expected == _doctrine_expectation(source, output), case_id
        for index in range(5):
            if expected[index] == measured[index]:
                continue
            divergent_params.append(f"{case_id}-{PATH_IDS[index]}")
            if measured[index] == "P":
                holes.add(case_id)
            else:
                false_blocks.add(case_id)

    assert not holes & false_blocks
    assert len(holes) == 16
    assert len(false_blocks) == 12
    assert len(divergent_params) == 120

    # 3. каждое расхождение обязано нести механизм, и наоборот
    assert set(DIVERGENCE_MECHANISM) == holes | false_blocks
    for case_id, mechanism in DIVERGENCE_MECHANISM.items():
        assert mechanism.strip(), case_id
        assert "law_enrichment_validation.py:" in mechanism, case_id
        # открытое расхождение не имеет права носить метку закрытия
        assert "ЗАКРЫТА ВОЛНОЙ" not in mechanism, case_id

    # 3-бис. ИСТОРИЯ ВОЛНЫ 9 РАБОТАЕТ СТОРОЖЕМ.  Причины 43 закрытых случаев
    #        (173 пары «случай x путь») не выброшены, а перенесены в
    #        CLOSED_BY_WAVE9 — и каждый случай оттуда ОБЯЗАН совпадать с
    #        доктриной всеми пятью буквами.  Поэтому повторное открытие дыры
    #        нельзя провести тихо: чтобы вернуть в таблицу measured='P', его
    #        придётся либо оставить здесь (падение), либо вынести случай из
    #        истории (падение на равенстве множеств ниже и на счётчике).
    columns = {case[0]: (case[3], case[4]) for case in CASES}
    assert len(CLOSED_BY_WAVE9) == 43
    assert not set(CLOSED_BY_WAVE9) & set(DIVERGENCE_MECHANISM)
    assert set(CLOSED_BY_WAVE9) <= set(columns)
    for case_id, closed_reason in CLOSED_BY_WAVE9.items():
        expected_column, measured_column = columns[case_id]
        assert measured_column == expected_column, case_id
        assert expected_column == "RRRRR", case_id
        assert "ЗАКРЫТА ВОЛНОЙ 9" in closed_reason, case_id
        assert "law_enrichment_validation.py:" in closed_reason, case_id

    # 4. контрольная тройка КАЖДОГО носителя: гейты этого источника живые.
    #    Сетка семейства заморожена целиком: переименовать случай в обход
    #    доктрины («invented-actor» → «nom-extra») нельзя, не уронив её.
    measured_by_id = {case[0]: case[4] for case in CASES}
    family_grid = (
        "ctl-faithful", "ctl-swap-patient", "ctl-swap-actor",
        "nom-faithful", "nom-bare", "nom-swap-patient", "nom-swap-actor",
        "nom-invented-actor", "nom-invented-term", "nom-invented-amount",
        "nom-invented-article", "nom-prohibition", "nom-plus-sanction",
    )
    for family in ("impose", "assign", "annul", "seize", "deprive", "charge"):
        assert {
            case_id[len(family) + 1:]
            for case_id in case_ids
            if case_id.startswith(f"{family}-")
        } == set(family_grid), family
    for family in ("impose", "assign", "annul", "seize", "deprive", "charge"):
        assert measured_by_id[f"{family}-ctl-swap-patient"] == "RRRRR", family
        assert measured_by_id[f"{family}-ctl-swap-actor"] == "RRRRR", family
    for case_id in ("impose", "assign", "annul", "seize", "charge"):
        assert measured_by_id[f"{case_id}-ctl-faithful"] == "PPPPP", case_id
    assert measured_by_id["rev-ctl-faithful"] == "PPPPP"
    assert measured_by_id["rev-ctl-swap-patient"] == "RRRRR"
    assert measured_by_id["rev-ctl-swap-actor"] == "RRRRR"

    # 5. ловушка обвязки, слой 1: R на штрафной ноге засчитывается только при
    #    доказанной живости обеих штрафных ног на ТОМ ЖЕ источнике
    live_penalty_sources = {
        case[1] for case in CASES if case[4][3] == "P" and case[4][4] == "P"
    }
    unproven = {
        case[1] for case in CASES if "R" in (case[4][3], case[4][4])
    } - live_penalty_sources
    assert unproven == PENALTY_LEGS_UNPROVEN_SOURCES

    # 6. ловушка обвязки, слой 2: причина заморожена для каждого отказа
    #    штрафных ног, для каждого ложного блока И (волна 9) для ВСЕХ ПЯТИ
    #    путей каждого закрытого случая.  Последнее добавлено потому, что
    #    «дыра закрыта» без названной причины неотличимо от «отказ приехал
    #    от посторонней ветви»: закрытие обязано держаться на том гейте,
    #    который назван в CLOSED_BY_WAVE9, а не на предусловии обвязки.
    expected_kind_keys = {
        (case[0], PATH_IDS[index])
        for case in CASES
        for index in range(5)
        if case[4][index] == "R"
        and (
            index in (3, 4)
            or case[3][index] == "P"
            or case[0] in CLOSED_BY_WAVE9
        )
    }
    assert set(REJECTION_KIND) == expected_kind_keys
    assert len(REJECTION_KIND) == 353
    assert set(REJECTION_KIND.values()) <= set(REJECTION_SUBSTRING)

    # 7. совпадающие пары (source, output) обязаны совпадать и в замере
    assert len(DUPLICATE_PROBES) == 4
    by_id = {case[0]: case for case in CASES}
    for group in DUPLICATE_PROBES:
        pairs = {(by_id[case_id][1], by_id[case_id][2]) for case_id in group}
        assert len(pairs) == 1, group
        assert len({by_id[case_id][4] for case_id in group}) == 1, group

    # 8. трёхрегионная граница: именно она — главный вывод класса
    region_free = (
        "bnd-bad-np", "bnd-bad-np-dot", "bnd-bad-np-genitive",
        "bnd-bad-np-prep", "bnd-bad-np-colon", "bnd-bad-dash",
        "bnd-bad-participle",
    )
    region_blind = (
        "bnd-bad-copula", "bnd-bad-light-verb", "bnd-bad-short-participle",
        "bnd-bad-passive-finite", "bnd-bad-infinitive",
    )
    for case_id in region_free:
        assert measured_by_id[case_id] == "PPPPP", case_id
        assert measured_by_id[case_id.replace("bad", "good")] == "PPPPP"
    for case_id in region_blind:
        assert measured_by_id[case_id] == "RRRRR", case_id
        assert measured_by_id[case_id.replace("bad", "good")] == "RRRRR"
    assert measured_by_id["bnd-bad-finite"] == "RRRRR"
    assert measured_by_id["bnd-good-finite"] == "PPPPP"

    # 9. ВОЛНА 9: ссылка на корень сверяется с ЖИВЫМ файлом валидатора.
    #    Волна 9 сдвинула его на 1375 строк; координаты, которые никто не
    #    сверяет, тихо превращаются в украшение, и «доказанный» механизм
    #    начинает указывать в пустоту.
    validator_lines = (
        Path(law_enrichment_validation.__file__)
        .read_text(encoding="utf-8")
        .splitlines()
    )
    for number, anchor in ROOT_ANCHORS.items():
        assert anchor in validator_lines[number - 1], (number, anchor)
    cited = {
        int(number)
        for reason in (*DIVERGENCE_MECHANISM.values(), *CLOSED_BY_WAVE9.values())
        for number in re.findall(r"\b\d{4,6}\b", reason)
    }
    cited |= {
        int(number)
        for number in re.findall(
            r"(?:law_enrichment_validation\.py|там же):(\d{4,6})",
            __doc__ or "",
        )
    }
    assert cited == set(ROOT_ANCHORS), cited ^ set(ROOT_ANCHORS)


def _kind_params() -> tuple[object, ...]:
    by_id = {case[0]: case for case in CASES}
    params = []
    for (case_id, path_id), kind in sorted(REJECTION_KIND.items()):
        case = by_id[case_id]
        params.append(
            pytest.param(
                ALL_OUTPUT_PATHS[PATH_IDS.index(path_id)],
                case[1],
                case[2],
                kind,
                id=f"{case_id}-{path_id}",
            )
        )
    return tuple(params)


@pytest.mark.parametrize(
    ("validate", "source", "output", "kind"),
    _kind_params(),
)
def test_nominal_rejection_kinds(
    validate: RelationValidator,
    source: str,
    output: str,
    kind: str,
) -> None:
    """Отказ обязан приходить от ТОЙ ЖЕ ветви, что и при первичном замере.

    Без этого теста отказ по предусловию обвязки неотличим от сработавшего
    гейта, и матрица выглядела бы зелёной там, где класс не проверяется вовсе.
    """

    with pytest.raises(ValueError) as excinfo:
        validate(source, output)
    assert REJECTION_SUBSTRING[kind] in str(excinfo.value)
